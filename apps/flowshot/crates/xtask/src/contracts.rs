use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
    process,
    time::{SystemTime, UNIX_EPOCH},
};

use flowshot_core::contracts::{
    AppErrorCode, AppErrorDto, BuildInfoDto, EmptyRequest, command_descriptors,
    workspace_declarations,
};
use serde_json::json;
use sha2::{Digest, Sha256};
use ts_rs::{Config, TS};

const GENERATOR_VERSION: &str = "1.1.0";
const GENERATED_RELATIVE: &str = "src/generated/contracts";
const SOURCE_FILES: [&str; 4] = [
    "crates/core/src/contracts/mod.rs",
    "crates/core/src/contracts/common.rs",
    "crates/core/src/contracts/error.rs",
    "crates/core/src/contracts/build_info.rs",
];

pub fn run(mut args: impl Iterator<Item = String>) -> Result<String, String> {
    let mut check = false;
    let mut check_determinism = false;
    let mut out_dir = None;

    while let Some(argument) = args.next() {
        match argument.as_str() {
            "--check" => check = true,
            "--check-determinism" => check_determinism = true,
            "--out-dir" => {
                let value = args
                    .next()
                    .ok_or_else(|| "--out-dir requires a path".to_owned())?;
                out_dir = Some(PathBuf::from(value));
            }
            unknown => return Err(format!("unknown contracts option `{unknown}`")),
        }
    }

    let root = repository_root();
    if check_determinism {
        verify_determinism(&root)?;
    }

    let destination = out_dir.unwrap_or_else(|| root.join(GENERATED_RELATIVE));
    if check {
        check_destination(&root, &destination)?;
        Ok(format!(
            "contracts are current in {}",
            display_path(&root, &destination)
        ))
    } else {
        write_contracts(&destination)?;
        Ok(format!(
            "generated contracts in {}",
            display_path(&root, &destination)
        ))
    }
}

fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn display_path(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

fn camel(name: &str) -> String {
    let mut words = name.split('_');
    let mut value = words.next().unwrap_or_default().to_owned();
    for word in words {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            value.extend(first.to_uppercase());
            value.push_str(chars.as_str());
        }
    }
    value
}
fn generated_files() -> Result<BTreeMap<&'static str, String>, String> {
    let config = Config::default();
    let commands = command_descriptors(&config);
    let header = format!(
        "// @generated by flowshot-xtask contracts v{GENERATOR_VERSION}.\n\
         // Rust sources are authoritative. Do not edit this file.\n\n"
    );

    let mut declarations = vec![
        AppErrorCode::decl(&config),
        AppErrorDto::decl(&config),
        EmptyRequest::decl(&config),
        BuildInfoDto::decl(&config),
    ];
    declarations.extend(workspace_declarations(&config));
    let types = format!(
        "{header}{}",
        declarations
            .into_iter()
            .map(|d| format!("export {d}\n"))
            .collect::<Vec<_>>()
            .join("\n")
    );
    let mut imports = BTreeSet::from(["AppErrorDto".to_owned()]);
    for command in &commands {
        imports.insert(command.request_type.clone());
        if command.transport != "binary" {
            imports.insert(command.response_type.clone());
        }
    }
    let mut commands_ts = format!(
        "{header}import {{ invoke }} from \"@tauri-apps/api/core\";\nimport type {{ {} }} from \"./types\";\n\nexport const commandNames = {{\n",
        imports.into_iter().collect::<Vec<_>>().join(", ")
    );
    for command in &commands {
        let name = camel(command.name);
        writeln!(commands_ts, "  {name}: \"{}\",", command.name).map_err(|e| e.to_string())?;
    }
    commands_ts.push_str("} as const;\n\nexport type CommandError = AppErrorDto;\n\n");
    for command in &commands {
        let name = camel(command.name);
        let default = if matches!(command.name, "get_build_info" | "list_workspaces") {
            " = {}"
        } else {
            ""
        };
        let response = if command.transport == "binary" {
            "ArrayBuffer"
        } else {
            &command.response_type
        };
        writeln!(commands_ts,"export async function {name}(request: {}{default}): Promise<{response}> {{\n  return invoke<{response}>(commandNames.{name}, {{ request }});\n}}\n",command.request_type).map_err(|e|e.to_string())?;
    }
    let index = format!(
        "{header}export * from \"./commands\";\n\
         export type * from \"./types\";\n"
    );

    let manifest = serde_json::to_string_pretty(&json!({
        "schemaVersion": 1,
        "generatorVersion": GENERATOR_VERSION,
        "commands": commands,
    }))
    .map_err(|error| format!("failed to serialize command manifest: {error}"))?
        + "\n";

    Ok(BTreeMap::from([
        ("commands.ts", format!("{}\n", commands_ts.trim_end())),
        ("index.ts", index),
        ("manifest.json", manifest),
        ("types.ts", types),
    ]))
}

fn write_contracts(destination: &Path) -> Result<(), String> {
    fs::create_dir_all(destination).map_err(|error| {
        format!(
            "failed to create contract directory {}: {error}",
            destination.display()
        )
    })?;

    for (name, content) in generated_files()? {
        let path = destination.join(name);
        fs::write(&path, content)
            .map_err(|error| format!("failed to write {}: {error}", path.display()))?;
    }
    Ok(())
}

fn check_destination(root: &Path, destination: &Path) -> Result<(), String> {
    let expected = generated_files()?;
    let expected_names = expected.keys().copied().collect::<BTreeSet<_>>();
    let mut drift = Vec::new();

    for (name, content) in expected {
        let path = destination.join(name);
        match fs::read_to_string(&path) {
            Ok(actual) if actual == content => {}
            Ok(_) => drift.push(format!("{name} differs")),
            Err(_) => drift.push(format!("{name} is missing")),
        }
    }

    if let Ok(entries) = fs::read_dir(destination) {
        for entry in entries.flatten() {
            let name = entry.file_name();
            let name = name.to_string_lossy();
            if entry.path().is_file() && !expected_names.contains(name.as_ref()) {
                drift.push(format!("{name} is unexpected"));
            }
        }
    }

    check_lock(root, &mut drift)?;
    check_n02_lock(root, &mut drift)?;

    if drift.is_empty() {
        Ok(())
    } else {
        drift.sort();
        Err(format!("contract drift:\n- {}", drift.join("\n- ")))
    }
}

const N02_SOURCES: &[&str] = &[
    "crates/core/src/contracts/N02_workspace.rs",
    "crates/core/src/contracts/N02_path.rs",
];
fn check_lock(root: &Path, drift: &mut Vec<String>) -> Result<(), String> {
    check_node_lock(root, drift, "N00", &SOURCE_FILES)
}
fn check_n02_lock(root: &Path, drift: &mut Vec<String>) -> Result<(), String> {
    check_node_lock(root, drift, "N02", N02_SOURCES)
}
fn check_node_lock(
    root: &Path,
    drift: &mut Vec<String>,
    node: &str,
    sources: &[&str],
) -> Result<(), String> {
    let lock_path = root.join(format!("contracts/locks/{node}.json"));
    let bytes = fs::read(&lock_path)
        .map_err(|error| format!("failed to read {}: {error}", lock_path.display()))?;
    let lock: serde_json::Value = serde_json::from_slice(&bytes)
        .map_err(|error| format!("failed to parse {}: {error}", lock_path.display()))?;

    let spec = fs::read(root.join("SPEC.md"))
        .map_err(|error| format!("failed to read SPEC.md: {error}"))?;
    let spec_text =
        std::str::from_utf8(&spec).map_err(|error| format!("SPEC.md is not UTF-8: {error}"))?;
    let spec_version = spec_text
        .lines()
        .find_map(|line| line.strip_prefix("version: "))
        .ok_or_else(|| "SPEC.md has no version".to_owned())?;
    let mut spec_digest = String::with_capacity(64);
    for byte in Sha256::digest(&spec) {
        write!(&mut spec_digest, "{byte:02x}")
            .map_err(|error| format!("failed to encode SPEC digest: {error}"))?;
    }
    let commands = command_descriptors(&Config::default());
    let names = commands
        .iter()
        .filter(|command| {
            if node == "N00" {
                command.name == "get_build_info"
            } else {
                command.name != "get_build_info"
            }
        })
        .map(|command| command.name)
        .collect::<Vec<_>>();
    for (field, expected) in [
        ("schema_version", json!(1)),
        ("node_id", json!(node)),
        ("status", json!("frozen")),
        ("spec_version", json!(spec_version)),
        ("spec_sha256", json!(spec_digest)),
        ("source_files", json!(sources)),
        (
            "source_hash_algorithm",
            json!("sha256(path + NUL + bytes + NUL, in source_files order)"),
        ),
        ("source_sha256", json!(source_digest_for(root, sources)?)),
        ("commands", json!(names)),
        ("generator_version", json!(GENERATOR_VERSION)),
    ] {
        if lock[field] != expected {
            drift.push(format!(
                "contracts/locks/{node}.json has an invalid {field}"
            ));
        }
    }
    if lock["frozen_at"]
        .as_str()
        .is_none_or(|value| value.trim().is_empty())
    {
        drift.push(format!("contracts/locks/{node}.json is missing frozen_at"));
    }
    Ok(())
}

fn source_digest_for(root: &Path, sources: &[&str]) -> Result<String, String> {
    let mut hasher = Sha256::new();
    for relative in sources {
        let path = root.join(relative);
        let bytes =
            fs::read(&path).map_err(|error| format!("failed to read {relative}: {error}"))?;
        hasher.update(relative.as_bytes());
        hasher.update([0]);
        hasher.update(bytes);
        hasher.update([0]);
    }
    let mut encoded = String::with_capacity(64);
    for byte in hasher.finalize() {
        write!(&mut encoded, "{byte:02x}")
            .map_err(|error| format!("failed to encode source digest: {error}"))?;
    }
    Ok(encoded)
}

fn verify_determinism(root: &Path) -> Result<(), String> {
    let first = temporary_directory("first");
    let second = temporary_directory("second");

    let result = (|| {
        write_contracts(&first)?;
        write_contracts(&second)?;
        compare_directories(&first, &second)
    })();

    let _ = fs::remove_dir_all(&first);
    let _ = fs::remove_dir_all(&second);

    result.map_err(|error| format!("{error} (repository: {})", root.display()))
}

fn temporary_directory(label: &str) -> PathBuf {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_nanos();
    std::env::temp_dir().join(format!(
        "flowshot-contracts-{}-{label}-{nanos}",
        process::id()
    ))
}

fn compare_directories(first: &Path, second: &Path) -> Result<(), String> {
    let expected = generated_files()?;
    for name in expected.keys() {
        let first_bytes = fs::read(first.join(name))
            .map_err(|error| format!("failed to read first {name}: {error}"))?;
        let second_bytes = fs::read(second.join(name))
            .map_err(|error| format!("failed to read second {name}: {error}"))?;
        if first_bytes != second_bytes {
            return Err(format!("non-deterministic generated file: {name}"));
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn isolated_generations_are_byte_identical() {
        verify_determinism(&repository_root()).expect("generation should be deterministic");
    }

    #[test]
    fn drift_check_names_the_changed_file() {
        let destination = temporary_directory("drift");
        write_contracts(&destination).expect("fixture generation should succeed");
        fs::write(destination.join("types.ts"), "changed").expect("fixture should mutate");

        let error = check_destination(&repository_root(), &destination)
            .expect_err("the actual checker must reject changed output");
        let _ = fs::remove_dir_all(&destination);
        assert!(error.contains("types.ts differs"));
    }

    #[test]
    fn frozen_lock_rejects_metadata_tampering() {
        let original = repository_root();
        let fixture = temporary_directory("lock-metadata");
        fs::create_dir_all(fixture.join("contracts/locks")).expect("fixture directory");
        for source in SOURCE_FILES.into_iter().chain(["SPEC.md"]) {
            let destination = fixture.join(source);
            fs::create_dir_all(destination.parent().expect("parent")).expect("source directory");
            fs::copy(original.join(source), destination).expect("copy source");
        }
        let original_lock: serde_json::Value = serde_json::from_slice(
            &fs::read(original.join("contracts/locks/N00.json")).expect("read frozen lock"),
        )
        .expect("parse frozen lock");
        for (field, invalid) in [
            ("schema_version", json!(2)),
            ("node_id", json!("N09")),
            ("spec_version", json!("0.0.0")),
            ("spec_sha256", json!("tampered")),
            ("source_files", json!([])),
            ("source_hash_algorithm", json!("md5")),
            ("commands", json!(["other_command"])),
            ("frozen_at", json!(null)),
        ] {
            let mut lock = original_lock.clone();
            lock[field] = invalid;
            fs::write(fixture.join("contracts/locks/N00.json"), lock.to_string())
                .expect("write lock");
            let mut drift = Vec::new();
            check_lock(&fixture, &mut drift).expect("read valid JSON");
            assert!(!drift.is_empty(), "tampered {field} must be rejected");
        }
        fs::remove_dir_all(fixture).expect("remove own fixture");
    }

    #[test]
    fn n02_frozen_lock_rejects_metadata_and_source_tampering() {
        let original = repository_root();
        let fixture = temporary_directory("n02-lock");
        fs::create_dir_all(fixture.join("contracts/locks")).unwrap();
        for source in N02_SOURCES.iter().copied().chain(["SPEC.md"]) {
            let destination = fixture.join(source);
            fs::create_dir_all(destination.parent().unwrap()).unwrap();
            fs::copy(original.join(source), destination).unwrap();
        }
        let original_lock: serde_json::Value =
            serde_json::from_slice(&fs::read(original.join("contracts/locks/N02.json")).unwrap())
                .unwrap();
        let lock_path = fixture.join("contracts/locks/N02.json");
        fs::write(&lock_path, original_lock.to_string()).unwrap();
        let mut drift = Vec::new();
        check_n02_lock(&fixture, &mut drift).unwrap();
        assert!(drift.is_empty(), "untampered fixture: {drift:?}");
        for (field, invalid) in [
            ("schema_version", json!(2)),
            ("node_id", json!("N00")),
            ("status", json!("draft")),
            ("spec_version", json!("0")),
            ("spec_sha256", json!("wrong")),
            ("source_files", json!([])),
            ("source_hash_algorithm", json!("md5")),
            ("source_sha256", json!("wrong")),
            ("commands", json!([])),
            ("generator_version", json!("0")),
            ("frozen_at", json!("")),
        ] {
            let mut lock = original_lock.clone();
            lock[field] = invalid;
            fs::write(&lock_path, lock.to_string()).unwrap();
            let mut drift = Vec::new();
            check_n02_lock(&fixture, &mut drift).unwrap();
            assert!(!drift.is_empty(), "tampered {field}");
        }
        fs::write(&lock_path, original_lock.to_string()).unwrap();
        fs::write(fixture.join(N02_SOURCES[0]), "changed source").unwrap();
        let mut drift = Vec::new();
        check_n02_lock(&fixture, &mut drift).unwrap();
        assert!(drift.iter().any(|entry| entry.contains("source_sha256")));
        fs::remove_dir_all(fixture).unwrap();
    }

    #[test]
    fn generated_output_contains_no_absolute_repository_path() {
        let root = repository_root();
        let root_text = root.to_string_lossy();
        for content in generated_files()
            .expect("output should render")
            .into_values()
        {
            assert!(!content.contains(root_text.as_ref()));
        }
    }
}
