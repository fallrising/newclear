  location /grafana/ {
    proxy_pass http://grafana_upstream/;
    proxy_set_header Host \$host;
    proxy_set_header X-Real-IP \$remote_addr;
  }

  # location /llm/ {
  #   proxy_pass http://nine_router_upstream/;
  #   proxy_set_header Host \$host;
  #   proxy_set_header X-Real-IP \$remote_addr;
  #   proxy_http_version 1.1;
  #   proxy_buffering off;
  #   proxy_read_timeout 3600s;
  # }

  # Example business app slots — point these at your compose services
  # after joining network platform_edge:
  #
  # location /app-a/ {
  #   proxy_pass http://app_a:8080/;
  # }
  # location /app-b/ {
  #   proxy_pass http://app_b:8080/;
  # }

  location / {
    return 200 'platform edge ok — add app routes in nginx/conf.d\n';
    add_header Content-Type text/plain;
  }
