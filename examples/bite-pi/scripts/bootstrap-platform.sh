    "nine": {
      "baseUrl": "http://127.0.0.1:20128/v1",
      "api": "openai-completions",
      "apiKey": "NINE_ROUTER_API_KEY"
    }
  }
}
EOF

cat > "$OUT/clients/opencode.jsonc.example" <<'EOF'
