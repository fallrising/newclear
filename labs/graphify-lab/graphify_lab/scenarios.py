"""Acceptance scenarios against the real, installed Graphify CLI and MCP server.

Fixtures are deliberately small enough to audit by hand. No graph is fabricated:
every assertion reads output generated by an upstream subprocess. Timings measure
this fixture workload, include the costs stated beside them, and are not a claim
about LLM tokens, arbitrary natural-language retrieval, or other machines.
"""

from __future__ import annotations

import asyncio
from datetime import timedelta
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import re
import shutil
import statistics
import subprocess
import sys
import time
from typing import Any, Callable


LAB = Path(__file__).resolve().parents[1]
FIXTURES = LAB / "fixtures"
SAMPLES = 5


def _require(condition: bool, reason: str) -> None:
    if not condition:
        raise RuntimeError(reason)


def _environment() -> dict[str, str]:
    # Use only this suite's declared Graphify settings. An ambient force/output/
    # tuning flag is not represented by the checked fixture/requirements hashes.
    env = {key: value for key, value in os.environ.items() if not key.startswith("GRAPHIFY_")}
    env["GRAPHIFY_NO_TIPS"] = "1"
    env["GRAPHIFY_QUERY_LOG_DISABLE"] = "1"
    return env


def _clean(value: Any, output: Path) -> Any:
    """Keep evidence portable; full raw graphs remain in the ignored run dir."""
    if isinstance(value, dict):
        return {key: _clean(item, output) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_clean(item, output) for item in value]
    if isinstance(value, str):
        return value.replace(str(output), "<run>").replace(str(LAB), "<lab>")
    return value


def _command(
    args: list[str], *, cwd: Path, output: Path, expected: int = 0,
    overrides: dict[str, str] | None = None,
) -> dict[str, Any]:
    env = _environment()
    env.update(overrides or {})
    start = time.perf_counter()
    proc = subprocess.run(
        [sys.executable, "-I", "-m", "graphify", *args], cwd=cwd, env=env,
        capture_output=True, text=True, timeout=120,
    )
    seconds = time.perf_counter() - start
    result = {
        "command": ["python", "-I", "-m", "graphify", *args],
        "exit_code": proc.returncode,
        "seconds": round(seconds, 6),
        "stdout": proc.stdout,
        "stderr": proc.stderr,
        "stdout_bytes": len(proc.stdout.encode("utf-8")),
    }
    if proc.returncode != expected:
        raise RuntimeError(
            f"Expected exit {expected}, got {proc.returncode}: "
            f"{_clean(result, output)}"
        )
    return result


def _read_graph(path: Path) -> dict[str, Any]:
    graph = json.loads(path.read_text(encoding="utf-8"))
    _require(bool(graph.get("nodes")), "Graph contains no nodes")
    _require(bool(graph.get("links", graph.get("edges"))), "Graph contains no edges")
    return graph


def _edges(graph: dict[str, Any]) -> list[dict[str, Any]]:
    return graph.get("links", graph.get("edges", []))


def _symbol(graph: dict[str, Any], label: str, source_file: str) -> dict[str, Any]:
    nodes = [n for n in graph["nodes"]
             if n.get("label") == label and n.get("source_file") == source_file]
    _require(len(nodes) == 1, f"Expected one {label} in {source_file}; found {len(nodes)}")
    return nodes[0]


def _calls(graph: dict[str, Any], source: str, target: str) -> list[dict[str, Any]]:
    return [e for e in _edges(graph)
            if e.get("relation") == "calls"
            and e.get("_src", e.get("source")) == source
            and e.get("_tgt", e.get("target")) == target]


def _node_evidence(node: dict[str, Any]) -> dict[str, Any]:
    return {key: node.get(key) for key in ("id", "label", "source_file", "source_location")}


def _sizes(root: Path) -> dict[str, int]:
    files = [p for p in root.rglob("*") if p.is_file()]
    return {"files": len(files), "logical_bytes": sum(p.stat().st_size for p in files)}


def _timing(values: list[float]) -> dict[str, Any]:
    return {
        "samples": len(values), "seconds": [round(v, 6) for v in values],
        "median_seconds": round(statistics.median(values), 6),
        "min_seconds": round(min(values), 6), "max_seconds": round(max(values), 6),
    }


def _error_text(exc: BaseException) -> str:
    if isinstance(exc, BaseExceptionGroup):
        return f"{type(exc).__name__}: " + "; ".join(_error_text(child) for child in exc.exceptions)
    return f"{type(exc).__name__}: {exc}"


async def _mcp_probe(graph: Path, node_id: str, expected_nodes: int, output: Path) -> dict[str, Any]:
    from mcp import ClientSession, StdioServerParameters
    from mcp.client.stdio import stdio_client

    params = StdioServerParameters(
        command=sys.executable, args=["-I", "-m", "graphify.serve", "--graph", str(graph)],
        cwd=str(output), env=_environment(),
    )

    def text_result(result: Any) -> str:
        error = getattr(result, "is_error", getattr(result, "isError", False))
        _require(not error, f"MCP returned an error: {result}")
        return "\n".join(block.text for block in result.content if hasattr(block, "text"))

    sessions: list[dict[str, Any]] = []
    # A second subprocess proves the persisted graph works without in-memory state.
    for sequence in range(2):
        started = time.perf_counter()
        with (output / f"mcp-{sequence + 1}.stderr.log").open("w", encoding="utf-8") as log:
            async with stdio_client(params, errlog=log) as (read, write):
                timeout = timedelta(seconds=20) if importlib.metadata.version("mcp").startswith("1.") else 20.0
                async with ClientSession(read, write, read_timeout_seconds=timeout) as session:
                    initialized = await session.initialize()
                    tools = await session.list_tools()
                    names = sorted(tool.name for tool in tools.tools)
                    _require(
                        {"query_graph", "get_node", "graph_stats", "shortest_path"} <= set(names),
                        "MCP server does not expose the expected real tools",
                    )
                    stats = text_result(await session.call_tool("graph_stats", {}))
                    _require(f"Nodes: {expected_nodes}\n" in stats, "MCP graph_stats node count mismatch")
                    node = text_result(await session.call_tool("get_node", {"node_id": node_id}))
                    _require("apply_discount()" in node and "pricing.py L4" in node,
                             "MCP get_node did not recover the source symbol")
                    query = {"question": "apply_discount", "depth": 2,
                             "token_budget": 1000, "context_filter": ["call"]}
                    first_start = time.perf_counter()
                    first = text_result(await session.call_tool("query_graph", query))
                    first_seconds = time.perf_counter() - first_start
                    _require("submit_order()" in first and "apply_discount()" in first,
                             "MCP query did not return expected call context")
                    _require("unrelated_healthcheck()" not in first,
                             "Context filter unexpectedly included unrelated function")
                    timings: list[float] = []
                    results = []
                    for _ in range(SAMPLES if sequence == 0 else 1):
                        t0 = time.perf_counter()
                        answer = text_result(await session.call_tool("query_graph", query))
                        timings.append(time.perf_counter() - t0)
                        _require(answer == first, "Repeated MCP query changed without source changes")
                        results.append(len(answer.encode("utf-8")))
                    path = text_result(await session.call_tool("shortest_path", {
                        "source": "api_checkout", "target": "pricing_apply_discount",
                    }))
                    _require("2 hops" in path and "submit_order()" in path,
                             "MCP did not recover the known directed call chain")
                    sessions.append({
                        "server": initialized.model_dump(by_alias=True)["serverInfo"],
                        "protocol_version": initialized.model_dump(by_alias=True)["protocolVersion"],
                        "tools": names, "stats": stats, "node": node,
                        "query": first, "directed_path": path,
                        "first_query_seconds": round(first_seconds, 6),
                        "warm_query": _timing(timings), "response_bytes": results,
                        "session_seconds": round(time.perf_counter() - started, 6),
                    })
    _require(sessions[0]["node"] == sessions[1]["node"], "Reopened MCP session changed node details")
    return {"transport": "stdio", "network_service": False, "sessions": sessions,
            "reopen_same_node": True, "benchmark_note": "Warm timings include local stdio round trip, exclude process startup."}


def run_suite(
    output: Path, reference_source: Path | None = None,
    reference_graph: Path | None = None,
) -> dict[str, Any]:
    """Run bounded synthetic-source scenarios; return and write portable evidence.

    The optional reference arguments are reserved for caller integration. Real
    repository acceptance is performed by the lab's outer runner; it is not
    silently considered covered by these fixtures.
    """
    if reference_source is not None or reference_graph is not None:
        raise ValueError("Real-repository probes belong to the outer runner; do not pass reference arguments here")
    output = output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    source = output / "python-shop"
    shutil.copytree(FIXTURES / "python-shop", source)
    graph_parent = output / "graphs" / "python-shop"
    graph_path = graph_parent / "graphify-out" / "graph.json"
    report: dict[str, Any] = {
        "schema": 1, "status": "failed", "graphify_version": importlib.metadata.version("graphifyy"),
        "python_version": sys.version.split()[0],
        "workload": "auditable synthetic Python shop and TypeScript dependency injection fixtures",
        "source_hashes": {str(p.relative_to(FIXTURES)): hashlib.sha256(p.read_bytes()).hexdigest()
                          for p in sorted(FIXTURES.rglob("*")) if p.is_file()},
        "cases": [], "limitations": [
            "Static source analysis is not proof of runtime reachability or a complete test selection system.",
            "Cross-repository typed member-call success is a TypeScript fixture; it is not arbitrary HTTP service resolution.",
            "Graphify query performs graph neighborhood retrieval; rg performs exact text matching. Latencies are not equivalent quality scores.",
            "Five repeated samples are descriptive local timings, not a statistically representative performance benchmark.",
            "Reported logical bytes are file contents, not allocated filesystem blocks, dependency footprint, or token counts.",
            "Upstream path exits 0 when both nodes exist but no directed path exists; consumers must inspect the answer, not only the exit status.",
            "Graphify query token_budget is a soft budget and can be exceeded; this suite records response bytes, not a hard token ceiling.",
            "Native HTML export contains a vis-network script URL on unpkg.com; generation and embedded data are verified, browser interaction and CDN availability are not.",
            "Fixture provenance is the recorded content hashes. An upstream graph built inside a Git checkout can inherit the enclosing Git HEAD even when the fixture is untracked.",
        ],
    }
    state: dict[str, Any] = {}

    def case(identifier: str, ac: list[str], name: str, action: Callable[[], Any]) -> None:
        started = time.perf_counter()
        row: dict[str, Any] = {"id": identifier, "ac": ac, "name": name}
        try:
            row["evidence"] = action()
            row["status"] = "passed"
        except Exception as exc:
            row["status"] = "failed"
            row["error"] = _error_text(exc)
        row["seconds"] = round(time.perf_counter() - started, 6)
        report["cases"].append(_clean(row, output))

    def build_and_navigate() -> dict[str, Any]:
        cold = _command(["extract", str(source), "--code-only", "--out", str(graph_parent)],
                        cwd=output, output=output)
        graph = _read_graph(graph_path)
        _require(graph.get("graph", {}).get("graphify_version") == report["graphify_version"],
                 "Graph producer version does not match installed package")
        discount = _symbol(graph, "apply_discount()", "pricing.py")
        order = _symbol(graph, "submit_order()", "orders.py")
        checkout = _symbol(graph, "checkout()", "api.py")
        test = _symbol(graph, "test_submit_order()", "tests/test_orders.py")
        _require(discount["source_location"] == "L4", "Incorrect discount definition line")
        _require("def apply_discount" in (source / "pricing.py").read_text().splitlines()[3],
                 "Graph location does not point to the actual source declaration")
        for caller, callee in ((checkout, order), (order, discount), (test, order)):
            _require(bool(_calls(graph, caller["id"], callee["id"])),
                     f"Missing known call {caller['label']} -> {callee['label']}")
        query = _command(["query", "apply_discount", "--graph", str(graph_path),
                          "--context", "call", "--budget", "1000"], cwd=output, output=output)
        _require("submit_order()" in query["stdout"], "query omitted the known caller")
        _require("unrelated_healthcheck()" not in query["stdout"], "query included unrelated function")
        explain = _command(["explain", discount["id"], "--graph", str(graph_path)],
                           cwd=output, output=output)
        _require("pricing.py L4" in explain["stdout"], "explain omitted exact source location")
        path = _command(["path", checkout["id"], discount["id"], "--graph", str(graph_path)],
                        cwd=output, output=output)
        _require("2 hops" in path["stdout"] and "submit_order()" in path["stdout"],
                 "Known directed call path was not recovered")
        missing = _command(["query", "zz_nonexistent_symbol_942771", "--graph", str(graph_path)],
                           cwd=output, output=output, expected=4)
        reverse = _command(["path", discount["id"], checkout["id"], "--graph", str(graph_path)],
                           cwd=output, output=output)
        _require(reverse["stdout"].startswith("No directed path found"),
                 "Reverse-path negative did not report that no directed path exists")
        exported = _command(["export", "html", "--graph", str(graph_path)], cwd=output, output=output)
        html_path = graph_path.with_name("graph.html")
        html = html_path.read_text(encoding="utf-8")
        _require(html_path.stat().st_size > 1000 and "new vis.Network" in html,
                 "HTML export lacks the native graph viewer")
        _require(all(n["id"] in html for n in (checkout, order, discount)),
                 "HTML export lost the known call-chain nodes")
        _require("const RAW_NODES" in html and "const RAW_EDGES" in html,
                 "HTML export lacks embedded graph data")
        state.update(graph=graph, discount=discount, cold=cold, query=query)
        return {"nodes": len(graph["nodes"]), "edges": len(_edges(graph)),
                "oracle_nodes": [_node_evidence(n) for n in (checkout, order, discount, test)],
                "oracle_call_edges": [e for e in _edges(graph) if e.get("relation") == "calls"],
                "cold_build": cold, "query": query, "explain": explain, "directed_path": path,
                "no_match": missing, "reverse_path_negative": reverse,
                "native_html": {"command": exported, "path": str(html_path),
                                "bytes": html_path.stat().st_size,
                                "known_nodes_embedded": True,
                                "external_scripts": re.findall(r'<script[^>]+src="([^"]+)"', html),
                                "browser_interaction_verified": False}}

    case("DEV-01", ["AC-02", "AC-08"], "Code map, exact source and directed call chain", build_and_navigate)

    def impact() -> dict[str, Any]:
        result = _command(["affected", "pricing_apply_discount", "--relation", "calls", "--depth", "3",
                           "--graph", str(graph_path)], cwd=output, output=output)
        expected = ["submit_order()", "checkout()", "test_submit_order()"]
        _require(all(f"- {name} [calls]" in result["stdout"] for name in expected),
                 "affected omitted an expected caller or test")
        _require("unrelated_healthcheck" not in result["stdout"], "affected included unrelated function")
        _require("tests/test_orders.py:L5" in result["stdout"], "affected omitted test call-site provenance")
        return {"expected_callers": expected, "unrelated_function_excluded": True,
                "affected": result, "scope": "Known static calls in this fixture only; no test execution or completeness claim."}

    case("DEV-02", ["AC-04"], "Change impact and test-call-site evidence", impact)

    def timings_and_mcp() -> dict[str, Any]:
        graph = state["graph"]
        before = hashlib.sha256(graph_path.read_bytes()).hexdigest()
        warm = _command(["extract", str(source), "--code-only", "--out", str(graph_parent)],
                        cwd=output, output=output)
        after = hashlib.sha256(graph_path.read_bytes()).hexdigest()
        _require(before == after, "No-change extraction rewrote the graph content")
        _require("Nothing to" in warm["stdout"] or "unchanged" in warm["stdout"].lower()
                 or "no changes" in warm["stdout"].lower(), "No-change build did not report a cache skip")
        cli_samples, rg_samples, rg_bytes = [], [], []
        rg_path = shutil.which("rg")
        _require(rg_path is not None, "rg is required for the exact-search baseline")
        query_args = ["query", "apply_discount", "--graph", str(graph_path), "--context", "call", "--budget", "1000"]
        for _ in range(SAMPLES):
            result = _command(query_args, cwd=output, output=output)
            _require("submit_order()" in result["stdout"], "Timed CLI query returned an invalid answer")
            cli_samples.append(result["seconds"])
            started = time.perf_counter()
            search = subprocess.run([rg_path, "--line-number", "--fixed-strings", "apply_discount", ".", "--glob", "*.py"],
                                    cwd=source, capture_output=True, text=True, timeout=30)
            rg_samples.append(time.perf_counter() - started)
            _require(search.returncode == 0 and "def apply_discount" in search.stdout,
                     "rg baseline failed to find the declaration")
            rg_bytes.append(len(search.stdout.encode("utf-8")))
        mcp = asyncio.run(asyncio.wait_for(_mcp_probe(graph_path, "pricing_apply_discount", len(graph["nodes"]), output), timeout=90))
        _require(hashlib.sha256(graph_path.read_bytes()).hexdigest() == before,
                 "Read-only CLI or MCP query changed graph.json")
        return {"source": _sizes(source), "index_directory": _sizes(graph_path.parent),
                "graph_json_bytes": graph_path.stat().st_size,
                "cold_build_seconds": state["cold"]["seconds"], "unchanged_build": warm,
                "same_graph_sha256": before, "cli_query_including_startup": _timing(cli_samples),
                "rg_exact_search_including_startup": _timing(rg_samples), "rg_response_bytes": rg_bytes,
                "cli_query_response_bytes": state["query"]["stdout_bytes"], "mcp": mcp,
                "queries_preserved_graph_hash": True,
                "comparison": "Same symbol, different tasks: Graphify returns a relation neighborhood; rg returns matching text lines."}

    case("DEV-03", ["AC-08", "AC-09"], "Cold/warm costs and two real MCP stdio sessions", timings_and_mcp)

    def incremental() -> dict[str, Any]:
        before = _read_graph(graph_path)
        _symbol(before, "legacy_total()", "pricing.py")
        pricing = source / "pricing.py"
        pricing.write_text(pricing.read_text(encoding="utf-8").replace("legacy_total", "shipping_quote"), encoding="utf-8")
        update = _command(["update", str(source)], cwd=source, output=output,
                          overrides={"GRAPHIFY_OUT": str(graph_path.parent)})
        graph = _read_graph(graph_path)
        added = _symbol(graph, "shipping_quote()", "pricing.py")
        _require(not any(n.get("label") == "legacy_total()" for n in graph["nodes"]),
                 "Deleted symbol survived incremental update")
        checkout = _symbol(graph, "checkout()", "api.py")
        order = _symbol(graph, "submit_order()", "orders.py")
        discount = _symbol(graph, "apply_discount()", "pricing.py")
        _require(bool(_calls(graph, checkout["id"], order["id"])) and bool(_calls(graph, order["id"], discount["id"])),
                 "Unchanged call edges disappeared after update")
        old = _command(["explain", "legacy_total", "--graph", str(graph_path)], cwd=output, output=output, expected=4)
        new = _command(["explain", added["id"], "--graph", str(graph_path)], cwd=output, output=output)
        _require("shipping_quote()" in new["stdout"], "New symbol is not queryable after update")
        return {"change": "Rename unused legacy_total to shipping_quote in copied fixture; do not mutate references.",
                "new_symbol": _node_evidence(added), "old_symbol_absent": True,
                "unchanged_call_chain_preserved": True, "update": update,
                "deleted_symbol_negative": old, "new_symbol_explain": new}

    case("DEV-04", ["AC-05"], "Incremental rename and removal without stale nodes", incremental)

    def cross_repository() -> dict[str, Any]:
        paths, builds, graphs = {}, {}, {}
        for name in ("ts-consumer", "ts-sdk", "ts-duplicate"):
            project = output / name
            shutil.copytree(FIXTURES / name, project)
            parent = output / "graphs" / name
            builds[name] = _command(["extract", str(project), "--code-only", "--out", str(parent)],
                                    cwd=output, output=output)
            paths[name] = parent / "graphify-out" / "graph.json"
            graphs[name] = _read_graph(paths[name])
        consumer = graphs["ts-consumer"]
        parked = [entry for n in consumer["nodes"] for entry in n.get("metadata", {}).get("unresolved_calls", [])]
        _require(any(p.get("callee") == "issue" and p.get("receiver_type") == "InvoiceClient" for p in parked),
                 "Consumer extraction did not preserve the unresolved typed call")
        _require(not any(e.get("context") == "cross_repo" for e in _edges(consumer)),
                 "Consumer alone unexpectedly contains a cross-repository edge")
        merged_path = output / "merged.json"
        merge = _command(["merge-graphs", str(paths["ts-consumer"]), str(paths["ts-sdk"]),
                          "--out", str(merged_path)], cwd=output, output=output)
        graph = _read_graph(merged_path)
        cross = [e for e in _edges(graph) if e.get("relation") == "calls" and e.get("context") == "cross_repo"]
        _require(len(cross) == 1, f"Expected one resolved cross-repository call, found {len(cross)}")
        edge = cross[0]
        _require(edge["source"] == "ts-consumer::app_checkoutapp_run"
                 and edge["target"] == "ts-sdk::invoice_invoiceclient_issue", "Merged call resolved to the wrong type")
        _require(edge.get("confidence") == "INFERRED" and edge.get("source_location") == "L7",
                 "Merged edge lost inference or call-site provenance")
        ids = [n["id"] for n in graph["nodes"]]
        _require(len(ids) == len(set(ids)), "Merged graph contains duplicate node IDs")
        _require(all(n.get("repo") and "::" in n["id"] for n in graph["nodes"] if n.get("source_file")),
                 "Merged source nodes lost repository namespaces")
        ambiguous_path = output / "ambiguous.json"
        ambiguity = _command(["merge-graphs", *[str(paths[n]) for n in ("ts-consumer", "ts-sdk", "ts-duplicate")],
                              "--out", str(ambiguous_path)], cwd=output, output=output)
        ambiguous = _read_graph(ambiguous_path)
        wrong_calls = [e for e in _edges(ambiguous) if e.get("relation") == "calls" and e.get("context") == "cross_repo"]
        _require(not wrong_calls, "Ambiguous receiver incorrectly resolved to a definite cross-repository call")
        same_name = _command(["explain", "InvoiceClient", "--graph", str(ambiguous_path)],
                             cwd=output, output=output, expected=3)
        return {"builds": builds, "parked_calls": parked, "merge": merge, "resolved_edge": edge,
                "unrelated_same_method_not_selected": True, "namespaced_source_nodes": True,
                "ambiguous_merge": ambiguity, "ambiguous_cross_repo_calls": len(wrong_calls),
                "ambiguous_label_exit": same_name,
                "scope": "Typed TypeScript member call only; merge does not itself recluster communities."}

    case("DEV-05", ["AC-06"], "Cross-repository typed calls and ambiguity refusal", cross_repository)
    report["status"] = "passed" if all(row["status"] == "passed" for row in report["cases"]) else "failed"
    report["passed"] = sum(row["status"] == "passed" for row in report["cases"])
    report["failed"] = sum(row["status"] == "failed" for row in report["cases"])
    report = _clean(report, output)
    (output / "report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return report


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    result = run_suite(args.output)
    print(json.dumps({key: result[key] for key in ("status", "passed", "failed")}, ensure_ascii=False))
    raise SystemExit(0 if result["status"] == "passed" else 1)
