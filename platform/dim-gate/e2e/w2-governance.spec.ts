for (const kind of ['redis', 'kafka'] as const) {
  test(`W2 AC-06/09/15/17: Admin ${kind} typed revision and disable refuse old changes without rewriting frozen snapshots`, async ({ page }, info) => {
    test.setTimeout(240_000)
    const health = captureBrowserHealth(page)
    health.expectedStatuses.add(409)
    try {
      await page.goto('rd')
      const originalResources = businessResources(await snapshot(page))
      const oldDraftId = await createResource(page, kind, { topic: 'w2-catalog-old-draft' })
      const oldSubmittedId = await createResource(page, kind, { topic: 'w2-catalog-old-submitted' })
      await act(page, '提交審核')
      const oldSnapshot = await snapshot(page)
      const oldDraft = changeById(oldSnapshot, oldDraftId)
      const oldSubmitted = changeById(oldSnapshot, oldSubmittedId)
      expect(oldSubmitted.catalogSnapshot?.revision).toBe(1)
      await become(page, 'user-admin')
      await page.goto(`admin/catalog?itemId=w2-catalog-${kind}`)
      await page.getByRole('textbox', { name: '變更理由', exact: true }).fill(`Govern ${kind} limits through visible typed editor`)
      await page.getByRole('button', { name: '建立下一版草稿', exact: true }).click()
      await expect(page.getByRole('heading', { name: kind === 'redis' ? 'Redis allocation 型別化草稿' : 'Kafka topic 型別化草稿', exact: true })).toBeVisible()
      const defaultLabel = kind === 'redis' ? '預設 · 配額 MiB' : '預設 · Partitions'
      const newDefault = kind === 'redis' ? '768' : '4'
      await page.getByRole('spinbutton', { name: defaultLabel, exact: true }).fill(newDefault)
      await page.getByRole('button', { name: '儲存草稿內容', exact: true }).click()
      await expect(page.getByRole('spinbutton', { name: defaultLabel, exact: true })).toHaveValue(newDefault)
      await expect.poll(async () => (await snapshot(page)).entities.catalogs.find(item => item.id === `w2-catalog-${kind}`)!.template.defaults).toEqual(kind === 'redis' ? { quotaMiB: 768 } : { partitions: 4, retentionHours: 72, throughputKiBPerSecond: 512 })
      await accessibleAtSizes(page, info, `${kind}-typed-editor`)
      await page.getByRole('button', { name: '發布 revision', exact: true }).click()
      await expect(page.locator('article')).toContainText('rev 2 · 已發布')
      expect(changeById(await snapshot(page), oldSubmittedId)).toEqual(oldSubmitted)
      await become(page, 'user-rd-commerce')
      await visitChange(page, 'rd', oldDraftId)
      await refuseAction(page, '提交審核', 'CATALOG_CHANGED')
      expect(changeById(await snapshot(page), oldDraftId)).toEqual(oldDraft)
      await become(page, 'user-ops')
      await visitChange(page, 'ops', oldSubmittedId)
      await refuseAction(page, '核准並保留配額', 'CATALOG_CHANGED')
      expect(changeById(await snapshot(page), oldSubmittedId)).toEqual(oldSubmitted)
      await become(page, 'user-rd-commerce')
      const disabledId = await createResource(page, kind, { topic: 'w2-catalog-disabled-pending' })
      await act(page, '提交審核')
      const beforeDisable = changeById(await snapshot(page), disabledId)
      expect(beforeDisable.catalogSnapshot?.revision).toBe(2)
      expect(beforeDisable.catalogSnapshot?.template.defaults).toEqual(kind === 'redis' ? { quotaMiB: 768 } : { partitions: 4, retentionHours: 72, throughputKiBPerSecond: 512 })
      await become(page, 'user-admin')
      await page.goto(`admin/catalog?itemId=w2-catalog-${kind}`)
      await page.getByRole('textbox', { name: '變更理由', exact: true }).fill('Stop new approvals while retaining immutable submitted history')
      await page.getByRole('button', { name: '停用新申請', exact: true }).click()
      await expect(page.locator('article')).toContainText('已停用')
      await become(page, 'user-ops')
      await visitChange(page, 'ops', disabledId)
      await refuseAction(page, '核准並保留配額', 'CATALOG_DISABLED')
      await page.reload()
      await expect(page.locator('.page-heading')).toContainText('待審核')
      await become(page, 'user-rd-commerce')
      await visitChange(page, 'rd', oldDraftId)
      await refuseAction(page, '提交審核', 'CATALOG_DISABLED')
      const final = await snapshot(page)
      expect(changeById(final, oldDraftId)).toEqual(oldDraft)
      expect(changeById(final, disabledId)).toEqual(beforeDisable)
      expect(changeById(final, oldSubmittedId)).toEqual(oldSubmitted)
      expect(businessResources(final)).toEqual(originalResources)
      await info.attach(`${kind}-governance-history.json`, { body: JSON.stringify({ oldDraft, oldSubmitted, beforeDisable, finalChanges: final.entities.changes, catalogs: final.entities.catalogs.filter(item => item.id === `w2-catalog-${kind}`) }), contentType: 'application/json' })
    } finally { await verifyBrowserHealth(page, info, health) }
  })
}

test('W2 AC-09/15: Admin UI grant revocation redacts objects then removes physical resource visibility after reload', async ({ page }, info) => {
  test.setTimeout(120_000)
  const health = captureBrowserHealth(page)
  health.expectedStatuses.add(404)
  try {
    await page.goto('rd')
    await become(page, 'user-ops')
    await page.goto('ops/caches/ci-idc-redis-01')
    await expect(page.getByText('w2-object-redis-data', { exact: true })).toBeVisible()
    const initial = await snapshot(page)
    await become(page, 'user-admin')
    await page.goto('admin/access')
    await page.getByRole('textbox', { name: '理由', exact: true }).fill('Revoke IDC resource management scope through Admin UI')
    const row = page.getByRole('row').filter({ has: page.getByText('grant-ops-idc', { exact: true }) })
    await expect(row).toContainText('user-ops')
    await row.getByRole('button', { name: '撤銷', exact: true }).click()
    await expect(row).toHaveCount(0)
    const revoked = await snapshot(page)
    expect(revoked.policyVersion).toBe(initial.policyVersion + 1)
    expect(businessResources(revoked)).toEqual(businessResources(initial))
    await become(page, 'user-ops')
    await page.goto('ops/caches/ci-idc-redis-01')
    // Project grants still authorize the physical CI, while the removed pool grant
    // immediately prevents access to explicit resource objects and bindings.
    await expect(page.getByRole('heading', { name: '影響範圍未完整授權', exact: true })).toBeVisible()
    await expect(page.locator('main')).not.toContainText('w2-object-redis-data')
    await expect(page.locator('main')).not.toContainText('w2-object-redis-commerce')
    for (const objectId of ['w2-object-redis-data', 'w2-object-redis-commerce']) {
      const denied = await raw(page, `/resource-objects/${objectId}`)
      expect(denied.status).toBe(404)
      expect(apiErrorSchema.safeParse(denied.payload).success).toBe(true)
      expect(denied.payload.data).toBeUndefined()
      expect(JSON.stringify(denied.payload)).not.toContain(objectId)
    }
    const parentProjects = initial.entities.cis.find(item => item.id === 'ci-idc-redis-01')!.visibilityProjectIds
    const projectGrants = initial.entities.assignments.filter(item => item.userId === 'user-ops' && item.role === 'ops' && item.scopeType === 'project' && parentProjects.includes(item.scopeId))
    expect(projectGrants.length).toBeGreaterThan(0)
    await become(page, 'user-admin')
    await page.goto('admin/access')
    await page.getByRole('textbox', { name: '理由', exact: true }).fill('Remove remaining project visibility to verify union-of-grants deep-read denial')
    for (const grant of projectGrants) {
      const projectRow = page.getByRole('row').filter({ has: page.getByText(grant.id, { exact: true }) })
      await projectRow.getByRole('button', { name: '撤銷', exact: true }).click()
      await expect(projectRow).toHaveCount(0)
    }
    await become(page, 'user-ops')
    await page.goto('ops/caches/ci-idc-redis-01')
    await expect(page.getByRole('heading', { name: '找不到這個資源或工作單', exact: true })).toBeVisible()
    await expect(page.locator('main')).not.toContainText('w2-object-redis-data')
    await expect(page.locator('main')).not.toContainText('w2-binding-data-redis')
    for (const path of ['/resource-inventory/ci-idc-redis-01', '/resource-objects/w2-object-redis-data', '/resource-objects/w2-object-redis-commerce']) {
      const denied = await raw(page, path)
      expect(denied.status).toBe(404)
      expect(apiErrorSchema.safeParse(denied.payload).success).toBe(true)
      expect(denied.payload.data).toBeUndefined()
      expect(JSON.stringify(denied.payload)).not.toMatch(/w2-object|w2-binding|commerce-dev|data-dev/)
    }
    await page.reload()
    await expect(page.getByRole('heading', { name: '找不到這個資源或工作單', exact: true })).toBeVisible()
    await page.goto('ops/caches')
    await expect(page.locator('main h1')).toHaveText('Redis 快取')
    await expect(page.locator('main')).not.toContainText('ci-idc-redis-01')
    const final = await snapshot(page)
    expect(businessResources(final)).toEqual(businessResources(initial))
    await info.attach('revoked-resource-scope.json', { body: JSON.stringify({ oldPolicyVersion: initial.policyVersion, newPolicyVersion: final.policyVersion, assignments: final.entities.assignments.filter(item => item.userId === 'user-ops') }), contentType: 'application/json' })
  } finally { await verifyBrowserHealth(page, info, health) }
})
