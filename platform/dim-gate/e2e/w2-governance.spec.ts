import { test, expect, type Page, type TestInfo } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { apiErrorSchema, type Snapshot } from '../src/domain/schemas'
import { captureBrowserHealth, verifyBrowserHealth } from './browser-health'
import { become, visitChange, act, ticks, createResource, readSnapshot, raw } from './w2-resource-helpers'

const snapshot = async (page: Page): Promise<Snapshot> => readSnapshot(page)
const changeById = (saved: Snapshot, id: string) => saved.entities.changes.find(item => item.id === id)!
const businessResources = (saved: Snapshot) => ({ objects: saved.entities.resourceObjects, bindings: saved.entities.resourceBindings, quotas: saved.entities.resourceQuotas })

async function accessibleAtSizes(page: Page, info: TestInfo, label: string) {
  for (const theme of ['light', 'dark']) {
    if (await page.locator('html').getAttribute('data-theme') !== theme) await page.getByRole('button', { name: theme === 'dark' ? '切換深色主題' : '切換淺色主題' }).click()
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: 1000 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${label}: ${theme} ${width}`).toBe(true)
      const violations = (await new AxeBuilder({ page }).analyze()).violations.filter(item => ['serious', 'critical'].includes(item.impact ?? ''))
      expect(violations, `${label}: ${theme} ${width}`).toEqual([])
      await info.attach(`${label}-${theme}-${width}`, { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
    }
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
}

async function refuseAction(page: Page, name: string, code: string) {
  await page.getByRole('button', { name, exact: true }).click()
  const dialog = page.getByRole('dialog', { name, exact: true })
  await expect(dialog).toBeVisible()
  const reason = dialog.getByRole('textbox', { name: '決策／操作理由' })
  if (await reason.count()) await reason.fill('Verify current template policy refuses this old request')
  await dialog.getByRole('button', { name: '確認操作', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText(code)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toHaveCount(0)
}

async function deliver(page: Page, id: string) {
  await become(page, 'user-ops')
  await visitChange(page, 'ops', id)
  await act(page, '核准並保留配額')
  await expect(page.locator('.page-heading')).toContainText('已核准，待執行')
  await act(page, '啟動資源執行')
  await ticks(page)
  await expect(page.locator('.page-heading')).toContainText('已成功')
}

test('W2 AC-04/07/09: Ops shared Redis resize needs independent approval and updates both consumers after execution', async ({ page }, info) => {
  test.setTimeout(180_000)
  const health = captureBrowserHealth(page)
  health.expectedStatuses.add(403)
  try {
    await page.goto('rd')
    await become(page, 'user-ops')
    await page.goto('ops/caches/ci-idc-redis-01')
    const initial = await snapshot(page)
    const article = page.locator('article#w2-object-redis-commerce')
    const trigger = article.getByRole('button', { name: '提出共享配額維護', exact: true })
    for (let index = 0; index < 80 && !await trigger.evaluate(el => el === document.activeElement); index++) await page.keyboard.press('Tab')
    await expect(trigger).toBeFocused()
    await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog', { name: 'Redis allocation 配額維護', exact: true })
    await expect(dialog).toBeVisible()
    expect(await dialog.evaluate(el => el.contains(document.activeElement))).toBe(true)
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(trigger).toBeFocused()
    await page.keyboard.press('Enter')
    await dialog.getByRole('spinbutton', { name: '期望配額 MiB', exact: true }).fill('2048')
    await dialog.getByRole('textbox', { name: '維護理由', exact: true }).fill('Shared Commerce allocation needs 2048 MiB for both consumers')
    await expect(dialog).toContainText('checkout')
    await expect(dialog).toContainText('storefront')
    expect((await new AxeBuilder({ page }).analyze()).violations.filter(item => ['serious', 'critical'].includes(item.impact ?? ''))).toEqual([])
    await dialog.getByRole('button', { name: '建立維護草稿', exact: true }).click()
    await expect(page.getByRole('heading', { name: '資源變更詳情', exact: true })).toBeVisible()
    const id = new URL(page.url()).pathname.split('/').at(-1)!
    await act(page, '提交審核')
    await expect(page.locator('.page-heading')).toContainText('待審核')
    await expect(page.getByRole('button', { name: '核准並保留配額', exact: true })).toHaveCount(0)
    const submitted = changeById(await snapshot(page), id)
    expect(submitted.requesterId).toBe('user-ops')
    expect(submitted.spec.applicationId).toBeUndefined()
    const selfApproval = await raw(page, `/changes/${id}/approve`, 'POST', { expectedVersion: submitted.version, reason: 'Direct self approval must fail' }, 'w2-browser-self-approval')
    expect(selfApproval.status).toBe(403)
    expect(selfApproval.payload.error.code).toBe('SELF_APPROVAL_DENIED')
    expect(changeById(await snapshot(page), id)).toEqual(submitted)
    await become(page, 'w2-user-ops-secondary')
    await visitChange(page, 'ops', id)
    await act(page, '核准並保留配額')
    await expect(page.locator('.page-heading')).toContainText('已核准，待執行')
    expect((await snapshot(page)).entities.resourceObjects).toEqual(initial.entities.resourceObjects)
    await become(page, 'user-ops')
    await visitChange(page, 'ops', id)
    await act(page, '啟動資源執行')
    await ticks(page, 2)
    await page.reload()
    await expect(page.locator('.page-heading')).toContainText('執行中')
    await ticks(page, 3)
    await expect(page.locator('.page-heading')).toContainText('已成功')
    const completed = await snapshot(page)
    const object = completed.entities.resourceObjects.find(item => item.id === 'w2-object-redis-commerce')!
    expect(object.spec).toEqual({ quotaMiB: 2048 })
    expect(completed.entities.resourceBindings).toEqual(initial.entities.resourceBindings)
    expect(completed.entities.resourceObjects.filter(item => item.id !== object.id)).toEqual(initial.entities.resourceObjects.filter(item => item.id !== object.id))
    expect(changeById(completed, id).decisions[0].actorId).toBe('w2-user-ops-secondary')
    expect(changeById(completed, id).specSnapshot).toEqual(submitted.specSnapshot)
    await become(page, 'user-rd-commerce')
    for (const app of ['checkout', 'storefront']) {
      await page.goto(`rd/apps/app-${app}/resources?environmentId=env-${app}-dev`)
      await expect(page.getByText('w2-object-redis-commerce', { exact: true })).toBeVisible()
      await expect(page.getByText('2048 MiB 配額', { exact: true })).toBeVisible()
    }
    await info.attach('shared-resize-canonical.json', { body: JSON.stringify({ id, object, change: changeById(completed, id), bindings: completed.entities.resourceBindings.filter(item => item.resourceObjectId === object.id) }), contentType: 'application/json' })
  } finally { await verifyBrowserHealth(page, info, health) }
})

