import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {telemetry,strictJson} from '../contracts/validation.ts';
import {sample} from './mock-agent.mjs';
const read=p=>JSON.parse(readFileSync(new URL('../contracts/'+p,import.meta.url),'utf8'));
const schema=read('telemetry.schema.json'),fixture=read('telemetry.fixture.json'),api=read('openapi.json');
const now=Date.parse(fixture.sent_at);
assert.deepEqual(telemetry(fixture,now),fixture);
assert.deepEqual(Object.keys(schema.properties).sort(),Object.keys(fixture).sort());
assert.deepEqual(schema.required.sort(),Object.keys(fixture).sort());
assert.deepEqual(Object.keys(schema.properties.metrics.properties).sort(),Object.keys(fixture.metrics).sort());
assert.deepEqual(Object.keys(sample('node_demo01',now)).sort(),Object.keys(fixture).sort());
assert.equal(schema.additionalProperties,false);
assert.equal(schema.properties.schema_version.const,fixture.schema_version);
assert.equal(api.openapi,'3.1.0');assert.equal(Object.keys(api.paths).length,8);
assert.equal(api.paths['/agent/v1/telemetry'].post.requestBody.content['application/json'].schema.$ref,'./telemetry.schema.json');
assert.throws(()=>telemetry({...fixture,command:'reboot'},now));
assert.throws(()=>strictJson('{"seq":1,"seq":2}'));
console.log('S0 contract shape, fixture, strict parser, and mock producer agree (8 operations).');
