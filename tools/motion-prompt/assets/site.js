/* Motion Prompt — gallery. Plain JS, no dependencies. Reads window.MP_CATALOG / MP_PROMPT (assets/catalog.js,
   generated by tools/build.mjs) and the packs registered through assets/runtime.js. */
(function () {
  'use strict';
  var CAT = window.MP_CATALOG, PROMPT = window.MP_PROMPT, MP = window.MotionPrompt;
  var $ = function (s, r) { return (r || document).querySelector(s); };
  var $$ = function (s, r) { return Array.prototype.slice.call((r || document).querySelectorAll(s)); };
  var root = document.documentElement;
  if (!CAT || !PROMPT || !MP) return;

  // ------------------------------------------------------------------ text
  var I18N = window.MP_I18N;

  // ------------------------------------------------------------------ state
  var store = {
    get: function (k) { try { return localStorage.getItem('motion-prompt:' + location.pathname + ':' + k); } catch (e) { return null; } },
    set: function (k, v) { try { localStorage.setItem('motion-prompt:' + location.pathname + ':' + k, v); } catch (e) { /* private mode etc. */ } },
  };
  var reduceMotion = window.matchMedia ? window.matchMedia('(prefers-reduced-motion: reduce)') : { matches: false };
  var darkQuery = window.matchMedia ? window.matchMedia('(prefers-color-scheme: dark)') : { matches: false };
  var state = {
    lang: root.lang === 'en' ? 'en' : 'zh-Hant',
    pack: 'all', cat: 'all', q: '',
    playing: !reduceMotion.matches,
    open: null,           // id shown in the detail view
    internalNav: 0,       // history entries this page pushed for the detail view
    picks: [],            // selected ids, in the order they were picked
    note: '',             // the one-line note that goes with the picks
    copyLang: 'zh-Hant',
  };
  var packBy = {}, elBy = {}, order = [];
  CAT.packs.forEach(function (p) { packBy[p.pack] = p; });
  CAT.elements.forEach(function (e, i) { elBy[e.id] = e; e._i = i; order.push(e.id); });

  function t(key, vars) {
    var s = I18N[state.lang][key];
    if (s == null) throw new Error('Missing interface text: ' + state.lang + '.' + key);
    if (vars) Object.keys(vars).forEach(function (k) { s = s.split('{' + k + '}').join(vars[k]); });
    return s;
  }
  function names(el) {
    var ja = state.lang === 'zh-Hant';
    return { main: ja ? el.name['zh-Hant'] + '（' + el.name.en + '）' : el.name.en, sub: '' };
  }
  function h(tag, attrs, kids) {
    var n = document.createElement(tag);
    if (attrs) Object.keys(attrs).forEach(function (k) {
      if (k === 'class') n.className = attrs[k];
      else if (k === 'text') n.textContent = attrs[k];
      else n.setAttribute(k, attrs[k]);
    });
    (kids || []).forEach(function (c) { if (c) n.appendChild(c); });
    return n;
  }

  // ------------------------------------------------------------------ packs (the drawing code)
  var ready = {}; // pack -> 'ok' | 'failed'
  function loadPack(p) {
    var lang = state.lang, key = p.pack + ':' + lang;
    ready[p.pack] = null;
    if (MP.packs[key]) { MP.packs[p.pack] = MP.packs[key]; ready[p.pack] = 'ok'; markDirty(p.pack); return; }
    var script = document.createElement('script');
    script.src = 'packs/' + p.pack + '/pack' + (lang === 'en' ? '.en' : '') + '.js';
    script.onload = function () {
      MP.packs[key] = MP.packs[p.pack];
      if (state.lang !== lang) { loadPack(p); return; }
      ready[p.pack] = 'ok'; markDirty(p.pack);
    };
    script.onerror = function () { ready[p.pack] = 'failed'; tiles.forEach(function(tl) { if (tl.el.pack === p.pack) breakTile(tl); }); };
    document.head.appendChild(script);
  }

  // ------------------------------------------------------------------ drawing
  var tiles = [];        // { el, a, canvas, ctx, visible, dirty, offset, broken }
  var detail = { canvas: $('#d-canvas'), ctx: null, scale: 1, dirty: false, el: null, broken: false, u: 0 };
  var STILL = 0.4; // paused views show this fraction of the loop, where most moves have something on screen
  var clock = 0, lastNow = 0;

  function paint(ctx, el, u, scale) {
    var reg = MP.packs[el.pack];
    var cell = reg && reg.cells[+el.no - 1];
    if (!cell) return false;
    var w = el.width, hgt = el.height;
    ctx.setTransform(1, 0, 0, 1, 0, 0); ctx.globalAlpha = 1; ctx.filter = 'none'; ctx.globalCompositeOperation = 'source-over';
    ctx.clearRect(0, 0, w * scale, hgt * scale);
    ctx.save();
    if (scale !== 1) ctx.scale(scale, scale);
    try { cell(ctx, w, hgt, u); } catch (e) { console.error(e); ctx.restore(); return false; }
    ctx.restore();
    return true;
  }
  function timeFor(el, offset) {
    var u = (clock + offset * el.cycle) % el.cycle;
    return u < 0 ? u + el.cycle : u;
  }
  function breakTile(tl) {
    if (tl.broken) return;
    tl.broken = true;
    tl.a.classList.add('is-broken');
    tl.a.appendChild(h('span', {class:'load-error', text:t('loadFailed')}));
  }
  function markDirty(pack) {
    tiles.forEach(function (tl) { if (!pack || tl.el.pack === pack) tl.dirty = true; });
    detail.dirty = true;
  }
  function frame(now) {
    requestAnimationFrame(frame);
    var dt = lastNow ? Math.min((now - lastNow) / 1000, 0.1) : 0;
    lastNow = now;
    if (state.playing) clock += dt;
    if (state.open) { // the gallery is covered: draw only the detail view
      var el = detail.el;
      if (el && !detail.broken && ready[el.pack] === 'ok' && (state.playing || detail.dirty)) {
        detail.dirty = false;
        if (state.playing) detail.u = (detail.u + dt) % el.cycle;
        if (!paint(detail.ctx, el, detail.u, detail.scale)) detail.broken = true;
      }
      return;
    }
    for (var i = 0; i < tiles.length; i++) {
      var tl = tiles[i];
      if (!tl.visible || tl.broken || ready[tl.el.pack] !== 'ok') continue;
      if (!state.playing && !tl.dirty) continue;
      tl.dirty = false;
      if (!paint(tl.ctx, tl.el, timeFor(tl.el, tl.offset), 1)) breakTile(tl);
    }
  }
  var io = 'IntersectionObserver' in window ? new IntersectionObserver(function (entries) {
    entries.forEach(function (en) {
      var tl = en.target._tile;
      if (!tl) return;
      tl.visible = en.isIntersecting;
      if (tl.visible) tl.dirty = true;
    });
  }, { rootMargin: '120px 0px' }) : null;

  // ------------------------------------------------------------------ gallery
  var grid = $('#grid');
  function buildGrid() {
    if (io) io.disconnect();
    tiles = [];
    grid.textContent = '';
    CAT.packs.forEach(function (p) {
      var list = h('div', { class: 'tiles' });
      CAT.elements.forEach(function (el) {
        if (el.pack !== p.pack) return;
        var nm = names(el);
        var canvas = h('canvas', { width: el.width, height: el.height, 'aria-hidden': 'true' });
        var a = h('a', { class: 'tile', href: '#' + el.id, 'data-id': el.id, 'aria-label': t('openLabel', { id: el.id, name: nm.main }) }, [
          h('span', { class: 'tile-stage', style: 'aspect-ratio:' + el.width + '/' + el.height }, [canvas]),
          h('span', { class: 'tile-cap' }, [
            h('span', { class: 'tile-id', text: el.id }),
            h('span', { class: 'tile-name', text: nm.main }),
            h('span', { class: 'tile-sub', text: nm.sub }),
          ]),
        ]);
        var pb = h('button', { type: 'button', class: 'tile-pick', 'aria-pressed': 'false', 'data-pick': el.id }, [
          pickBox(), h('span', { class: 'tile-pick-t' }),
        ]);
        var box = h('div', { class: 'tile-box' }, [a, pb]);
        var tl = { el: el, a: a, box: box, pick: pb, canvas: canvas, ctx: canvas.getContext('2d'), visible: !io, dirty: true, broken: false,
          offset: reduceMotion.matches ? STILL : (el._i * 0.6180339887) % 1 };
        a._tile = tl;
        pb.addEventListener('click', function () { togglePick(el.id); });
        markTile(tl);
        a.addEventListener('click', function (ev) {
          if (ev.metaKey || ev.ctrlKey || ev.shiftKey || ev.altKey || ev.button) return;
          state.internalNav += 1; // the hash change that follows adds one history entry
        });
        if (ready[el.pack] === 'failed') breakTile(tl);
        tiles.push(tl);
        list.appendChild(box);
        if (io) io.observe(a);
      });
      var sec = h('section', { class: 'pack', 'data-pack': p.pack, 'aria-labelledby': 'pack-' + p.pack }, [
        h('div', { class: 'pack-h' }, [
          h('h3', { id: 'pack-' + p.pack, text: p.title[state.lang] }),
          h('span', { text: '#' + p.first + '–' + p.last }),
        ]),
        list,
      ]);
      grid.appendChild(sec);
    });
    applyFilter();
  }

  function haystack(el) {
    var p = packBy[el.pack];
    var c = p.categories.filter(function (x) { return x.slug === el.category; })[0] || {};
    return ['#' + el.id, el.id, String(+el.id), el.slug, el.pack, el.name['zh-Hant'], el.name.en, el.meaning ? el.meaning['zh-Hant'] + ' ' + el.meaning.en : '', el.summary['zh-Hant'], el.summary.en,
      el.tags.join(' '), p.title['zh-Hant'], p.title.en, c['zh-Hant'] || '', c.en || ''].join(' ').toLowerCase();
  }
  function matches(el) {
    if (state.pack !== 'all' && el.pack !== state.pack) return false;
    if (state.cat !== 'all' && el.category !== state.cat) return false;
    if (!state.q) return true;
    if (!el._hay) el._hay = haystack(el);
    var terms = state.q.toLowerCase().replace(/＃/g, '#').split(/[\s　]+/).filter(Boolean);
    return terms.every(function (term) {
      if (/^#?\d{1,3}$/.test(term)) { // a number means an ID: "12", "012" and "#012" all find #012
        var d = term.replace('#', '');
        return el.id === ('000' + d).slice(-3) || (d.length === 3 && el.id === d);
      }
      return el._hay.indexOf(term) >= 0;
    });
  }
  var shown = order.slice();
  function applyFilter() {
    shown = [];
    tiles.forEach(function (tl) {
      var ok = matches(tl.el);
      tl.box.hidden = !ok;
      if (ok) shown.push(tl.el.id);
    });
    $$('.pack', grid).forEach(function (sec) { sec.hidden = !$('.tile-box:not([hidden])', sec); });
    $('#empty').hidden = shown.length > 0;
    $('#count').textContent = shown.length === CAT.count ? t('count', { n: CAT.count }) : t('countOf', { n: shown.length, total: CAT.count });
  }

  function chip(label, pressed, small, onClick) {
    var b = h('button', { type: 'button', class: 'chip', 'aria-pressed': pressed ? 'true' : 'false', text: label });
    if (small) b.appendChild(h('small', { text: small }));
    b.addEventListener('click', onClick);
    return b;
  }
  function buildChips() {
    var packs = $('#packs'), cats = $('#cats');
    packs.textContent = ''; cats.textContent = '';
    packs.appendChild(chip(t('all'), state.pack === 'all', String(CAT.count), function () { setFilter('all', 'all'); }));
    CAT.packs.forEach(function (p) {
      packs.appendChild(chip(p.title[state.lang], state.pack === p.pack, String(p.count), function () { setFilter(p.pack, 'all'); }));
    });
    var p = packBy[state.pack];
    cats.hidden = !p;
    if (!p) return;
    cats.appendChild(chip(t('allIn'), state.cat === 'all', '', function () { setFilter(state.pack, 'all'); }));
    p.categories.forEach(function (c) {
      cats.appendChild(chip(c[state.lang], state.cat === c.slug, '', function () { setFilter(state.pack, c.slug); }));
    });
  }
  function setFilter(pack, cat) {
    var focusIndex = $$('.chip').indexOf(document.activeElement);
    state.pack = pack; state.cat = cat;
    buildChips();
    applyFilter();
    var again = $$('.chip')[focusIndex]; // the chips were rebuilt: keep keyboard focus where it was
    if (focusIndex >= 0 && again) again.focus();
  }

  // ------------------------------------------------------------------ copy
  function copyText(text) {
    function legacy() {
      var ta = h('textarea', { 'aria-hidden': 'true', tabindex: '-1', style: 'position:fixed;top:0;left:0;width:1px;height:1px;opacity:0' });
      ta.value = text;
      var host = dlg.open ? dlg : document.body; // inside the modal, the rest of the page is inert
      var back = document.activeElement;
      host.appendChild(ta); ta.select();
      var ok = false;
      try { ok = document.execCommand('copy'); } catch (e) { ok = false; }
      host.removeChild(ta);
      if (back && back.focus) back.focus({ preventScroll: true });
      return ok;
    }
    if (navigator.clipboard && navigator.clipboard.writeText) {
      return navigator.clipboard.writeText(text).then(function () { return true; }, legacy);
    }
    return Promise.resolve(legacy());
  }
  function flash(btn, ok) {
    var msg = t(ok ? 'copied' : 'copyFailed');
    if (!btn._label) btn._label = btn.textContent;
    clearTimeout(btn._timer);
    btn.textContent = msg;
    btn.classList.add('is-done');
    (dlg.open ? $('#d-live') : $('#live')).textContent = msg;
    btn._timer = setTimeout(function () {
      btn.textContent = btn._label; btn._label = null; btn.classList.remove('is-done');
    }, 1600);
  }
  function resetFlash(btn) { clearTimeout(btn._timer); btn._label = null; btn.classList.remove('is-done'); }
  $$('[data-copy]').forEach(function (btn) {
    btn.addEventListener('click', function () {
      copyText($(btn.getAttribute('data-copy')).textContent.trim()).then(function (ok) { flash(btn, ok); });
    });
  });

  // ------------------------------------------------------------------ detail view
  var dlg = $('#detail');
  var codeCache = {};
  function fetchCode(id, lang) {
    var key = lang + '/' + id;
    if (!codeCache[key]) {
      codeCache[key] = fetch('api/v1/' + lang + '/e/' + id + '.txt').then(function (r) {
        if (!r.ok) throw new Error(String(r.status));
        return r.text();
      });
      codeCache[key].catch(function () { delete codeCache[key]; });
    }
    return codeCache[key];
  }
  function sizeDetailCanvas() {
    var el = detail.el;
    if (!el) return;
    var cssW = detail.canvas.parentNode.clientWidth || el.width;
    var want = Math.ceil(cssW * (window.devicePixelRatio || 1) / el.width);
    // Sharper drawing by scaling the context — only for packs whose code never addresses device pixels.
    var scale = packBy[el.pack].scalable ? Math.max(1, Math.min(3, want)) : 1;
    if (detail.canvas.width !== el.width * scale || detail.canvas.height !== el.height * scale) {
      detail.canvas.width = el.width * scale; detail.canvas.height = el.height * scale;
    }
    detail.scale = scale; detail.dirty = true;
  }
  function fillDetail(el) {
    var p = packBy[el.pack], nm = names(el), lang = state.lang;
    var c = p.categories.filter(function (x) { return x.slug === el.category; })[0];
    detail.el = el; detail.broken = false;
    detail.u = state.playing ? 0 : STILL * el.cycle; // start from the top of the move
    detail.ctx = detail.canvas.getContext('2d');
    detail.canvas.style.aspectRatio = el.width + '/' + el.height;
    $('#d-id').textContent = '#' + el.id;
    $('#d-where').textContent = p.title[lang] + (c ? ' / ' + c[lang] : '');
    $('#d-name').textContent = nm.main;
    $('#d-sub').textContent = t('size', { w: el.width, h: el.height, c: el.cycle });
    var mean = $('#d-meaning'), ask = $('#d-ask'), askH = $('#d-ask-h');
    mean.textContent = el.meaning ? el.meaning[lang] : ''; mean.hidden = !mean.textContent;
    ask.textContent = el.ask ? el.ask[lang] : ''; ask.hidden = askH.hidden = !ask.textContent;
    $('#d-summary').textContent = el.summary[lang];
    var spec = $('#d-spec'); spec.textContent = '';
    el.spec[lang].forEach(function (s) { spec.appendChild(h('li', { text: s })); });
    $('#d-use').textContent = el.use[lang];
    var tags = $('#d-tags'); tags.textContent = '';
    el.tags.forEach(function (s) { tags.appendChild(h('li', { text: s })); });
    updatePrompt();
    var kit = $('#d-kit'), txt = $('#d-txt');
    kit.href = 'api/v1/kit/' + lang + '/' + el.pack + '.js'; kit.textContent = t('kitLink', { pack: el.pack });
    txt.href = 'api/v1/' + lang + '/e/' + el.id + '.txt'; txt.textContent = t('txtLink', { id: el.id });
    var pre = $('#d-code'); pre.textContent = t('codeLoading');
    fetchCode(el.id, lang).then(function (code) {
      if (detail.el === el && state.lang === lang) pre.textContent = code;
    }, function () { if (detail.el === el) pre.textContent = t('codeFailed'); });
    var i = shown.indexOf(el.id);
    var list = i >= 0 ? shown : order; // opened by direct link while filtered out: step through everything
    i = list.indexOf(el.id);
    $('#d-prev').disabled = i <= 0; $('#d-next').disabled = i >= list.length - 1;
    $('#d-prev')._to = list[i - 1]; $('#d-next')._to = list[i + 1];
    markDetailPick();
    resetFlash($('#d-copy-prompt')); resetFlash($('#d-copy-code'));
    $('#d-copy-prompt').textContent = t('copyPrompt'); $('#d-copy-code').textContent = t('copyCode');
    document.title = '#' + el.id + ' ' + nm.main + ' | Motion Prompt';
  }
  var lastFocus = null;
  function openDetail(id) {
    var el = elBy[id];
    if (!el) return closeDetail(true);
    var first = !dlg.open;
    state.open = id;
    fillDetail(el);
    if (first) {
      lastFocus = document.activeElement;
      root.classList.add('modal-open');
      if (dlg.showModal) dlg.showModal(); else dlg.setAttribute('open', '');
      $('#d-name').focus({ preventScroll: true });
    }
    dlg.scrollTop = 0;
    sizeDetailCanvas();
  }
  function closeDetail(silent) {
    if (!state.open && !dlg.open) return;
    var id = state.open;
    state.open = null; detail.el = null;
    if (dlg.open) { if (dlg.close) dlg.close(); else dlg.removeAttribute('open'); }
    root.classList.remove('modal-open');
    document.title = t('title');
    markDirty();
    if (silent) return;
    var tile = id && $('.tile[data-id="' + id + '"]');
    var back = tile && !tile.parentNode.hidden ? tile : lastFocus;
    if (back && back.focus) back.focus({ preventScroll: true });
  }
  function hashId() {
    var m = /^#(\d{1,3})$/.exec(location.hash);
    return m ? ('000' + m[1]).slice(-3) : null;
  }
  function syncFromHash() {
    var id = hashId();
    if (id && elBy[id]) openDetail(id);
    else { closeDetail(false); if (id) announce(t('invalidLink')); }
  }
  function requestClose() { // "back" when this page opened the view, otherwise just drop the hash
    if (state.internalNav > 0) { state.internalNav -= 1; history.back(); return; }
    history.replaceState(null, '', location.pathname + location.search);
    syncFromHash();
  }
  function step(id) {
    if (!id) return;
    history.replaceState(null, '', '#' + id); // moving sideways must not pile up history entries
    openDetail(id);
  }
  window.addEventListener('hashchange', syncFromHash);
  window.addEventListener('popstate', syncFromHash);
  dlg.addEventListener('cancel', function (ev) { ev.preventDefault(); requestClose(); }); // Esc
  dlg.addEventListener('click', function (ev) { if (ev.target === dlg) requestClose(); }); // backdrop
  $('#d-close').addEventListener('click', requestClose);
  $('#d-prev').addEventListener('click', function () { step(this._to); });
  $('#d-next').addEventListener('click', function () { step(this._to); });
  dlg.addEventListener('keydown', function (ev) {
    if (ev.metaKey || ev.ctrlKey || ev.altKey) return;
    var tag = ev.target && ev.target.tagName;
    if (tag === 'PRE' || tag === 'INPUT' || tag === 'TEXTAREA' || tag === 'SELECT') return;
    if (ev.key === 'ArrowLeft') { ev.preventDefault(); step($('#d-prev')._to); }
    if (ev.key === 'ArrowRight') { ev.preventDefault(); step($('#d-next')._to); }
  });
  $('#d-copy-prompt').addEventListener('click', function () {
    var btn = this;
    copyText($('#d-prompt').textContent).then(function (ok) { flash(btn, ok); });
  });
  $('#d-copy-code').addEventListener('click', function () {
    var btn = this, el = detail.el;
    if (!el) return;
    fetchCode(el.id, state.lang).then(copyText).then(function (ok) { flash(btn, ok); }, function () { flash(btn, false); });
  });
  window.addEventListener('resize', function () { if (state.open) sizeDetailCanvas(); });

  // ------------------------------------------------------------------ local picks
  var SITE = new URL('./', document.baseURI).href;
  var PICK_KEY = 'mp-pick', NOTE_MAX = 300;
  var CHECK_SVG = '<svg viewBox="0 0 16 16" width="14" height="14"><path d="M3.5 8.4l3 3 6-6.6" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"/></svg>';
  var X_SVG = '<svg viewBox="0 0 16 16" width="14" height="14" aria-hidden="true"><path d="M4 4l8 8M12 4l-8 8" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round"/></svg>';
  var tray = $('#tray'), trayList = $('#tray-list'), trayToggle = $('#tray-toggle'), trayBody = $('#tray-body'), trayNote = $('#tray-note');
  var trayOpen = !(window.matchMedia && window.matchMedia('(max-width: 720px)').matches); // phones start folded

  function pickBox() { var s = h('span', { class: 'pick-box', 'aria-hidden': 'true' }); s.innerHTML = CHECK_SVG; return s; }
  function isPicked(id) { return state.picks.indexOf(id) >= 0; }
  function cleanIds(list) {
    var out = [];
    (list || []).forEach(function (x) {
      var m = /^#?(\d{1,3})$/.exec(String(x).trim());
      var id = m && ('000' + m[1]).slice(-3);
      if (id && elBy[id] && out.indexOf(id) < 0) out.push(id);
    });
    return out;
  }
  function loadSaved(key) {
    try { var d = JSON.parse(store.get(key) || 'null'); return d && typeof d === 'object' ? d : null; } catch (e) { return null; }
  }
  function savePicks() {
    var data = { ids: state.picks, note: state.note };
    store.set(PICK_KEY, JSON.stringify(data));
  }
  function readParams() {
    var q = new URLSearchParams(location.search);
    var savedLang = q.get('lang') || store.get('mp-lang');
    if (savedLang === 'en' || savedLang === 'zh-Hant') state.lang = savedLang;
    var copyLang = store.get('mp-copy-lang');
    state.copyLangExplicit = copyLang === 'en' || copyLang === 'zh-Hant';
    state.copyLang = state.copyLangExplicit ? copyLang : state.lang;
    var theme = store.get('mp-theme'); if (theme === 'dark' || theme === 'light') root.setAttribute('data-theme', theme);
    var pk = q.get('pack');
    if (pk && packBy[pk]) state.pack = pk;
    var saved = loadSaved(PICK_KEY);
    if (q.has('pick')) { // a shared selection wins over what this browser remembers
      state.picks = cleanIds(String(q.get('pick')).split(','));
      state.note = '';
      q.delete('pick');
      var rest = q.toString();
      history.replaceState(null, '', location.pathname + (rest ? '?' + rest : '') + location.hash);
      savePicks();
    } else if (saved) {
      state.picks = cleanIds(saved.ids);
      state.note = String(saved.note || '').slice(0, NOTE_MAX);
    }
  }
  function markTile(tl) {
    var on = isPicked(tl.el.id);
    tl.box.classList.toggle('is-picked', on);
    tl.pick.setAttribute('aria-pressed', on ? 'true' : 'false');
    tl.pick.setAttribute('aria-label', t(on ? 'unpickLabel' : 'pickLabel', { id: tl.el.id, name: names(tl.el).main }));
    tl.pick.lastChild.textContent = t(on ? 'picked' : 'pick');
  }
  function markDetailPick() {
    var el = detail.el, b = $('#d-pick');
    if (!el) return;
    var on = isPicked(el.id);
    b.setAttribute('aria-pressed', on ? 'true' : 'false');
    b.setAttribute('aria-label', t(on ? 'unpickLabel' : 'pickLabel', { id: el.id, name: names(el).main }));
    $('#d-pick-t').textContent = t(on ? 'picked' : 'pick');
  }
  function announce(msg) { (dlg.open ? $('#d-live') : $('#live')).textContent = msg; }
  function togglePick(id) {
    var el = elBy[id];
    if (!el) return;
    var i = state.picks.indexOf(id);
    if (i >= 0) state.picks.splice(i, 1); else state.picks.push(id);
    savePicks();
    tiles.forEach(function (tl) { if (tl.el.id === id) markTile(tl); });
    markDetailPick(); renderTray();
    announce(t(i >= 0 ? 'unpickedLive' : 'pickedLive', { id: id, name: names(el).main, n: state.picks.length }));
  }
  function renderTray() {
    var n = state.picks.length;
    tray.hidden = !n;
    root.classList.toggle('has-tray', !tray.hidden);
    $('#tray-count').textContent = t('trayCount', { n: n });
    $('#tray-empty').hidden = n > 0;
    var main = $('#tray-main');
    if (!main._label && !main._sending) main.textContent = t('copyPicked');
    main.disabled = !n || !!main._sending;
    $('#tray-copy').disabled = $('#tray-share').disabled = $('#tray-clear').disabled = !n;
    trayToggle.setAttribute('aria-expanded', trayOpen ? 'true' : 'false');
    trayBody.hidden = !trayOpen;
    if (trayNote.value !== state.note) trayNote.value = state.note;
    trayList.textContent = '';
    state.picks.forEach(function (id, i) {
      var el = elBy[id], nm = names(el);
      var open = h('a', { class: 'tray-name', href: '#' + id }, [h('span', { class: 'tray-id', text: '#' + id }), h('span', { class: 'tray-nm', text: nm.main })]);
      open.addEventListener('click', function (ev) {
        if (ev.metaKey || ev.ctrlKey || ev.shiftKey || ev.altKey || ev.button) return;
        if (hashId() !== id) state.internalNav += 1;
      });
      var x = h('button', { type: 'button', class: 'tray-x', 'aria-label': t('unpickLabel', { id: id, name: nm.main }) });
      x.innerHTML = X_SVG;
      x.addEventListener('click', function () {
        togglePick(id);
        var xs = $$('.tray-x', trayList), next = xs[Math.min(i, xs.length - 1)];
        if (next) next.focus(); else if (!tray.hidden) trayToggle.focus(); else $('#q').focus({ preventScroll: true });
      });
      trayList.appendChild(h('li', null, [h('span', { class: 'tray-n', 'aria-hidden': 'true', text: String(i + 1) }), open, x]));
    });
  }
  function updatePrompt() {
    $$('[data-copy-lang]').forEach(function(s) { s.value = state.copyLang; });
    if (detail.el) $('#d-prompt').textContent = PROMPT(detail.el, packBy[detail.el.pack].title[state.copyLang], state.copyLang, SITE);
  }
  $$('[data-copy-lang]').forEach(function(select) { select.addEventListener('change', function() {
    state.copyLangExplicit = true; state.copyLang = select.value; store.set('mp-copy-lang', state.copyLang); updatePrompt();
  }); });
  function pickedText() {
    var lang = state.copyLang, text = I18N[lang];
    var lines = [text.outIntro.replace('{n}', state.picks.length), ''];
    state.picks.forEach(function(id) { var el = elBy[id]; lines.push(PROMPT(el, packBy[el.pack].title[lang], lang, SITE), ''); });
    if (state.note) lines.push(text.outNote + ': ' + state.note);
    return lines.join('\n');
  }
  function copyPicked(btn) {
    if (!state.picks.length) return;
    copyText(pickedText()).then(function (ok) { flash(btn, ok); });
  }
  $('#tray-main').addEventListener('click', function () { copyPicked(this); });
  $('#tray-copy').addEventListener('click', function () { copyPicked(this); });
  $('#tray-share').addEventListener('click', function () {
    var btn = this;
    if (!state.picks.length) return;
    copyText(SITE + '?pick=' + state.picks.join(',')).then(function (ok) { flash(btn, ok); });
  });
  $('#tray-clear').addEventListener('click', function () {
    state.picks = []; savePicks();
    tiles.forEach(markTile); markDetailPick(); renderTray();
    announce(t('clearedLive'));
    if (!tray.hidden) trayToggle.focus(); else $('#q').focus({ preventScroll: true });
  });
  trayToggle.addEventListener('click', function () { trayOpen = !trayOpen; renderTray(); });
  trayNote.addEventListener('input', function () { state.note = trayNote.value.slice(0, NOTE_MAX); savePicks(); });
  $('#d-pick').addEventListener('click', function () { if (detail.el) togglePick(detail.el.id); });
  if ('ResizeObserver' in window) {
    new ResizeObserver(function () { root.style.setProperty('--tray-h', tray.offsetHeight + 'px'); }).observe(tray);
  }

  // ------------------------------------------------------------------ language, theme, playback
  function applyText() {
    var lang = state.lang;
    root.lang = lang;
    $$('[data-t]').forEach(function (n) { n.textContent = t(n.getAttribute('data-t'), { n: CAT.count }); });
    $$('[data-t-html]').forEach(function (n) { n.innerHTML = t(n.getAttribute('data-t-html')); }); // own strings only
    $$('[data-t-attr]').forEach(function (n) {
      n.getAttribute('data-t-attr').split(',').forEach(function (pair) {
        var kv = pair.split(':'); n.setAttribute(kv[0].trim(), t(kv[1].trim()));
      });
    });
    $$('[data-lang]').forEach(function (b) { b.setAttribute('aria-pressed', b.getAttribute('data-lang') === lang ? 'true' : 'false'); });
    $('#fact-count').textContent = CAT.count;
    $('#fact-packs').textContent = CAT.packs.length;
    $('#tsv-link').href = 'api/v1/' + lang + '/catalog.tsv';
    $$('[data-href-' + lang + ']').forEach(function (a) { a.href = a.getAttribute('data-href-' + lang); });
    $('#d-prev').setAttribute('aria-label', t('prev'));
    $('#d-next').setAttribute('aria-label', t('next'));
    $('#d-close').setAttribute('aria-label', t('close'));
    $('#q').value = state.q;
    if (!state.open) document.title = t('title');
    applyTheme(); applyPlay(); updatePrompt();
  }
  function setLang(lang) {
    if (lang === state.lang) return;
    if (!I18N[lang]) return;
    state.lang = lang;
    if (!state.copyLangExplicit) state.copyLang = lang;
    store.set('mp-lang', lang);
    if (/[?&]lang=/.test(location.search)) { // keep a deep-link language in step with the choice
      var q = new URLSearchParams(location.search); q.set('lang', lang);
      history.replaceState(history.state, '', location.pathname + '?' + q.toString() + location.hash);
    }
    applyText(); buildChips(); buildGrid(); renderTray();
    CAT.packs.forEach(loadPack);
    if (state.open) fillDetail(elBy[state.open]);
  }
  $$('[data-lang]').forEach(function (b) { b.addEventListener('click', function () { setLang(b.getAttribute('data-lang')); }); });

  function isDark() {
    var a = root.getAttribute('data-theme');
    return a ? a === 'dark' : darkQuery.matches;
  }
  function applyTheme() { $('#theme').setAttribute('aria-label', t(isDark() ? 'themeToLight' : 'themeToDark')); }
  $('#theme').addEventListener('click', function () {
    var next = isDark() ? 'light' : 'dark';
    root.setAttribute('data-theme', next);
    store.set('mp-theme', next);
    applyTheme();
  });
  if (darkQuery.addEventListener) darkQuery.addEventListener('change', applyTheme);

  function applyPlay() {
    var b = $('#play'), d = $('#d-play');
    b.setAttribute('aria-pressed', state.playing ? 'true' : 'false');
    b.setAttribute('aria-label', t(state.playing ? 'pauseLabel' : 'playLabel'));
    d.setAttribute('aria-pressed', state.playing ? 'true' : 'false');
    d.setAttribute('aria-label', t(state.playing ? 'pause' : 'play'));
    $('#play-t').textContent = t(state.playing ? 'pause' : 'play');
  }
  if (reduceMotion.addEventListener) reduceMotion.addEventListener('change', function(e) {
    if (e.matches) { state.playing = false; applyPlay(); markDirty(); }
  });
  function togglePlay() { state.playing = !state.playing; applyPlay(); }
  $('#play').addEventListener('click', togglePlay);
  $('#d-play').addEventListener('click', togglePlay);

  var q = $('#q');
  q.addEventListener('input', function () { state.q = q.value.trim(); applyFilter(); });
  document.addEventListener('keydown', function (ev) {
    if (ev.key !== '/' || ev.metaKey || ev.ctrlKey || ev.altKey || dlg.open) return;
    var tag = document.activeElement && document.activeElement.tagName;
    if (tag === 'INPUT' || tag === 'TEXTAREA' || tag === 'SELECT') return;
    ev.preventDefault(); q.focus();
  });

  // ------------------------------------------------------------------ start
  readParams();
  applyText();
  buildChips();
  buildGrid();
  renderTray();
  CAT.packs.forEach(loadPack);
  requestAnimationFrame(frame);
  syncFromHash();
  if ((state.pack !== 'all') && !hashId()) $('#gallery').scrollIntoView({ block: 'start' }); // a pack link opens the samples
})();
